window.initSiteLayout = function() {
  SiteComponents.mount();
  applyLanguage(window.CurrentLang);
  highlightActiveNav();
  updateCartBadge();

  // Bind footer WhatsApp community links from CONFIG
  if (window.CONFIG) {
    const groupEl = document.getElementById('footer-wa-group');
    if (groupEl && window.CONFIG.WHATSAPP_GROUP_URL) {
      groupEl.href = window.CONFIG.WHATSAPP_GROUP_URL;
    }
    const chanEl = document.getElementById('footer-wa-channel');
    if (chanEl && window.CONFIG.WHATSAPP_CHANNEL_URL) {
      chanEl.href = window.CONFIG.WHATSAPP_CHANNEL_URL;
    }
  }

  // Attach Lang Switcher Event
  const langBtn = document.getElementById('lang-toggle-btn');
  if (langBtn && langBtn.getAttribute && !langBtn.getAttribute('data-bound')) {
    langBtn.setAttribute('data-bound', 'true');
    langBtn.addEventListener('click', () => {
      window.CurrentLang = window.CurrentLang === 'en' ? 'ar' : 'en';
      localStorage.setItem('shemade_lang', window.CurrentLang);
      applyLanguage(window.CurrentLang);
      if (typeof window.onLanguageChanged === 'function') {
        window.onLanguageChanged(window.CurrentLang);
      }
    });
  }

  // Handle Search Form Submission
  const searchForms = document.querySelectorAll('.search-container');
  searchForms.forEach(form => {
    if (form && form.getAttribute && !form.getAttribute('data-bound')) {
      form.setAttribute('data-bound', 'true');
      form.addEventListener('submit', (e) => {
        e.preventDefault();
        const input = form.querySelector('input[name="q"]') || document.getElementById('navbar-search');
        if (input && input.value.trim()) {
          window.location.href = `search.html?q=${encodeURIComponent(input.value.trim())}`;
        }
      });
    }
  });
};

// Initialize immediately so paint happens with correct language & nav state
initSiteLayout();
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initSiteLayout);
}
