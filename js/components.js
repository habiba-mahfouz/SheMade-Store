// Initialize Site Layout & i18n
function applyLanguage(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  const dict = window.I18N_DICTIONARY[lang] || window.I18N_DICTIONARY.ar;
  const isAr = lang === 'ar';
  const currency = isAr ? 'ج.م' : 'EGP';

  // 1. Static i18n Elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // 2. Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // 3. Dynamic Products & Section Titles & Select Options ([data-en] and [data-ar])
  document.querySelectorAll('[data-en][data-ar]').forEach(el => {
    const val = isAr ? el.getAttribute('data-ar') : el.getAttribute('data-en');
    if (val) {
      el.textContent = val;
    }
  });

  // 4. Prices & Currency ([data-price])
  document.querySelectorAll('[data-price]').forEach(el => {
    const p = parseFloat(el.getAttribute('data-price')) || 0;
    el.textContent = `${Math.round(p)} ${currency}`;
  });

  // 5. Re-render Cart Page if available
  if (window.App && typeof window.App.updateCartDisplay === 'function') {
    window.App.updateCartDisplay();
  }
}

function highlightActiveNav() {
  const path = (window.location && window.location.pathname) ? window.location.pathname.toLowerCase() : '';
  
  if (path.endsWith('index.html') || path.endsWith('/') || path === '') {
    document.getElementById('nav-home')?.classList.add('active');
  } else if (path.includes('crochet')) {
    document.getElementById('nav-crochet')?.classList.add('active');
  } else if (path.includes('bead')) {
    document.getElementById('nav-beads')?.classList.add('active');
  } else if (path.includes('cart')) {
    document.getElementById('nav-cart')?.classList.add('active');
  }
}

function updateCartBadge() {
  const cart = JSON.parse(localStorage.getItem('shemade_cart') || '[]');
  const totalCount = cart.reduce((sum, item) => sum + (item.quantity || 1), 0);
  const badge = document.getElementById('cart-badge');
  if (badge) {
    if (totalCount > 0) {
      badge.textContent = totalCount;
      badge.classList.remove('d-none');
    } else {
      badge.classList.add('d-none');
    }
  }
}

